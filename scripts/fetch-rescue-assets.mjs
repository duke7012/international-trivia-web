// Rebuilds the rescue games' pictures from shared/rescue-bank.mjs. Run by hand when the bank changes:
//   node scripts/fetch-rescue-assets.mjs
// Flags:    REST Countries flag CDN -> public/flags/{iso2}.png (640 px wide)
// Outlines: geoBoundaries simplified ADM0 (CC-BY 4.0) -> server/rescue-outlines.mjs as SVG paths
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { BEAT_SETS, DOODLES } from "../shared/rescue-bank.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const flagDir = path.join(root, "public", "flags");
fs.mkdirSync(flagDir, { recursive: true });
const get = async (url) => { const r = await fetch(url); if (!r.ok) throw new Error(`${r.status} ${url}`); return r; };

// ---- flags ----
const codes = [...new Set([...BEAT_SETS.flatMap((s) => s.levels.flat()), ...DOODLES].map((x) => x.iso2))];
for (const code of codes) {
  const file = path.join(flagDir, `${code}.png`);
  if (!fs.existsSync(file)) fs.writeFileSync(file, Buffer.from(await (await get(`https://flags.restcountries.com/v5/w640/${code}.png`)).arrayBuffer()));
}
console.log(`flags: ${codes.length}`);

// ---- outlines ----
const ringArea = (r) => { let a = 0; for (let i = 0, j = r.length - 1; i < r.length; j = i++) a += (r[j][0] + r[i][0]) * (r[j][1] - r[i][1]); return Math.abs(a / 2); };
const bbox = (pts) => pts.reduce((b, [x, y]) => [Math.min(b[0], x), Math.min(b[1], y), Math.max(b[2], x), Math.max(b[3], y)], [Infinity, Infinity, -Infinity, -Infinity]);
const gap = (a, b) => Math.hypot(Math.max(0, a[0] - b[2], b[0] - a[2]), Math.max(0, a[1] - b[3], b[1] - a[3]));
// Douglas-Peucker on a closed ring: split at the point farthest from the start, simplify both halves.
function simplifyRing(r, tol) {
  let far = 0, best = -1;
  r.forEach(([x, y], i) => { const dd = Math.hypot(x - r[0][0], y - r[0][1]); if (dd > best) { best = dd; far = i; } });
  return [...simplify(r.slice(0, far + 1), tol).slice(0, -1), ...simplify(r.slice(far), tol)];
}
function simplify(pts, tol) {
  if (pts.length < 4) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [s, e] = stack.pop(); let best = 0, at = -1;
    const [x1, y1] = pts[s], [x2, y2] = pts[e], dx = x2 - x1, dy = y2 - y1, len = Math.hypot(dx, dy) || 1e-9;
    for (let i = s + 1; i < e; i++) { const dd = Math.abs(dy * pts[i][0] - dx * pts[i][1] + x2 * y1 - y2 * x1) / len; if (dd > best) { best = dd; at = i; } }
    if (best > tol) { keep[at] = 1; stack.push([s, at], [at, e]); }
  }
  return pts.filter((_, i) => keep[i]);
}

const outlines = {};
for (const ctry of DOODLES) {
  const meta = await (await get(`https://www.geoboundaries.org/api/current/gbOpen/${ctry.iso3}/ADM0/`)).json();
  const gj = await (await get(meta.simplifiedGeometryGeoJSON)).json();
  let rings = gj.features.flatMap((f) => (f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates)).map((p) => p[0]);
  if (ctry.crop) {
    const [w, s, e, n] = ctry.crop;
    rings = rings.filter((r) => { const b = bbox(r), cx = (b[0] + b[2]) / 2, cy = (b[1] + b[3]) / 2; return cx >= w && cx <= e && cy >= s && cy <= n; });
  }
  // Keep the main landmass and the islands near it (growing outwards), drop far-off territories.
  rings.sort((a, b) => ringArea(b) - ringArea(a));
  const main = rings[0], mainArea = ringArea(main), mb = bbox(main), reach = 0.5 * Math.max(mb[2] - mb[0], mb[3] - mb[1]);
  const kept = [main]; let pool = rings.slice(1).filter((r) => ringArea(r) >= mainArea * 0.002), grew = true;
  while (grew) {
    grew = false;
    pool = pool.filter((r) => { if (kept.some((k) => gap(bbox(k), bbox(r)) <= reach)) { kept.push(r); grew = true; return false; } return true; });
  }
  // Project: equirectangular, x squeezed by cos(latitude) at the centre, y flipped, fitted to 1000 units.
  const all = bbox(kept.flat()), lat0 = ((all[1] + all[3]) / 2) * (Math.PI / 180), k = Math.cos(lat0);
  const span = Math.max((all[2] - all[0]) * k, all[3] - all[1]), scale = 1000 / span;
  const proj = ([x, y]) => [(x - all[0]) * k * scale, (all[3] - y) * scale];
  const w = Math.round((all[2] - all[0]) * k * scale), h = Math.round((all[3] - all[1]) * scale);
  const paths = kept.map((r) => simplifyRing(r.map(proj), 2.2)).filter((r) => r.length >= 4);
  const dStr = paths.map((r) => "M" + r.map(([x, y]) => `${x.toFixed(0)} ${y.toFixed(0)}`).join("L") + "Z").join("");
  outlines[ctry.iso3] = { d: dStr, w, h };
  console.log(`${ctry.iso3}: ${kept.length}/${rings.length} parts, ${paths.reduce((n, r) => n + r.length, 0)} points`);
}
fs.writeFileSync(path.join(root, "server", "rescue-outlines.mjs"),
  "// Generated by scripts/fetch-rescue-assets.mjs from geoBoundaries (CC-BY 4.0, www.geoboundaries.org). Do not edit by hand.\n" +
  `export default ${JSON.stringify(outlines)};\n`);
console.log("outlines written");
