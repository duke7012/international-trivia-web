const inside = (x, y, poly) => {
  let hit = false;
  for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
    const [xi, yi] = poly[i], [xj, yj] = poly[j];
    if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) hit = !hit;
  }
  return hit;
};

// Dots as [x, y] in a 1000 x 500 box.
export function mapDots(step = 3.4) {
  const dots = [];
  for (let lat = 78; lat >= -56; lat -= step) {
    for (let lon = -176; lon <= 180; lon += step) {
      if (LAND.some((p) => inside(lon, lat, p))) dots.push([((lon + 180) / 360) * 1000, ((80 - lat) / 140) * 500]);
    }
  }
  return dots;
}

// The broken route: start, three checkpoints, end. Each leg is a gentle arc.
export const ROUTE = [[70, 250], [290, 330], [520, 170], [745, 320], [930, 190]];
export function legPath(i) {
  const [x0, y0] = ROUTE[i], [x1, y1] = ROUTE[i + 1];
  const mx = (x0 + x1) / 2, my = (y0 + y1) / 2 - 70;
  return `M${x0} ${y0} Q${mx} ${my} ${x1} ${y1}`;
}
